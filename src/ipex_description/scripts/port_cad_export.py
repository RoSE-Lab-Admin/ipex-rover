"""Port a Fusion 360 URDF export (fusion2urdf) into ipex_description.

Usage (from the repo root, on any computer with Python 3):
    python src/ipex_description/scripts/port_cad_export.py <export>_description

Writes urdf/ipex.xacro and copies the meshes into src/ipex_description. Then
rebuild ipex_description, check with xacro, and look at it in RViz.

What it changes from the export:
  - package:// paths -> ipex_description; robot name "full"
  - includes: ipex.ros2_control.xacro + sensors.xacro instead of .trans/.gazebo
  - joint "back_right_wheel_rev (1)" -> "back_right_wheel_rev"
  - each shoulder joint pitched so position 0 = drum axle level with the pivot
    (the firmware's 0 deg), measured from the export, so any exported arm pose works
  - IMU_rigid turned 180 deg about z if the export puts the IMU behind the
    center: the real IMU is front-right (avionics box installed turned around
    compared with the CAD, 2026-11-03). sensors.xacro cancels the turn so imu_link
    stays aligned with base_link; if the CAD gets fixed, set imu_link yaw back to 0.
"""
import glob
import math
import os
import re
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE)


def main(export_dir):
    xacros = [p for p in glob.glob(os.path.join(export_dir, 'urdf', '*.xacro'))
              if not p.endswith('materials.xacro')]
    if len(xacros) != 1:
        sys.exit(f'expected one robot xacro in {export_dir}/urdf, found {xacros}')
    t = open(xacros[0]).read()
    export_pkg = re.search(r'package://([^/]+)/', t).group(1)

    t = re.sub(r'<robot name="[^"]+"', '<robot name="full"', t, count=1)
    t = t.replace(f'package://{export_pkg}/', 'package://ipex_description/')
    t, n = re.subn(r'(<xacro:include[^\n]*/>\n)+',
                   '<xacro:include filename="materials.xacro" />\n'
                   '<xacro:include filename="ipex.ros2_control.xacro" />\n'
                   '<xacro:include filename="sensors.xacro" />\n', t, count=1)
    assert n == 1, 'includes not found'
    t = t.replace('"back_right_wheel_rev (1)"', '"back_right_wheel_rev"')

    def joint_xyz(name):
        m = re.search(r'<joint name="%s"[^>]*>\s*<origin xyz="([^"]+)"' % re.escape(name), t)
        assert m, f'joint {name} not found'
        return [float(v) for v in m.group(1).split()]

    notes = []
    for shoulder, drum in (('front_shoulder_rev', 'front_left_drum_rev'),
                           ('back_shoulder_rev', 'back_left_drum_rev')):
        x, _, z = joint_xyz(drum)
        raised = math.atan2(z, abs(x))
        pitch = raised if x > 0 else -raised   # front: +pitch lowers +x; rear: -pitch lowers -x
        pat = r'(<joint name="%s" type="continuous">\s*<origin xyz="[^"]+") rpy="0 0 0"' % shoulder
        t, n = re.subn(pat, r'\1 rpy="0 %.6f 0"' % pitch, t)
        assert n == 1, shoulder
        notes.append(f'{shoulder} pitched {math.degrees(pitch):+.2f} deg '
                     f'(exported {math.degrees(raised):.2f} deg raised)')

    pat = r'(<joint name="IMU_rigid" type="fixed">\s*<origin xyz=")([^"]+)" rpy="0 0 0"'
    m = re.search(pat, t)
    assert m, 'IMU_rigid not found'
    x, y, z = (float(v) for v in m.group(2).split())
    if x < 0:
        t = t[:m.start()] + m.group(1) + f'{-x:g} {-y:g} {z:g}" rpy="0 0 {math.pi:.6f}"' + t[m.end():]
        notes.append('IMU_rigid turned 180 deg about z (CAD has it rear-left; real IMU is front-right)')
    else:
        notes.append('IMU NOT turned: the export already has it in front. Set imu_link yaw to 0 in sensors.xacro.')

    header = (
        f'<!-- Roxey geometry, generated by scripts/port_cad_export.py from the CAD\n'
        f'     export "{os.path.basename(os.path.normpath(export_dir))}". Regenerate instead of editing.\n'
        + ''.join(f'       - {s}\n' for s in notes) +
        '     base_link: x forward (front arm end), y left, z up; origin midway\n'
        '     between the axles, 0.1525 m below them (2.5 mm above the tire tread). -->\n')
    t = t.replace('<robot name="full"', header + '<robot name="full"', 1)

    open(os.path.join(PKG, 'urdf', 'ipex.xacro'), 'w', newline='\n').write(t)
    meshes = glob.glob(os.path.join(export_dir, 'meshes', '*.stl'))
    for p in meshes:
        shutil.copy2(p, os.path.join(PKG, 'meshes'))
    print('\n'.join(notes))
    print(f'wrote urdf/ipex.xacro, copied {len(meshes)} meshes')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
